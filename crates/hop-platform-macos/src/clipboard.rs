//! The text clipboard: `NSPasteboard.generalPasteboard`, never waited on
//! for long (docs/M4-M5-DESIGN.md, "Text clipboard").
//!
//! Reading a pasteboard can wait on the app that copied: an app that
//! copies lazily is asked for its data only when someone reads it, and an
//! app that is busy answers late. So every call runs on a helper thread of
//! its own ("hop-clipboard", one call at a time), and the caller waits at
//! most [`CLIPBOARD_TIMEOUT`]. A call that takes longer returns an error;
//! its result, when it finally comes, is thrown away. A call that has not
//! even started by then never starts at all: a write landing seconds late
//! would replace whatever the user copied in the meantime.
//!
//! `NSPasteboard` is not tied to the main thread, so the helper uses it
//! directly, each call in an autorelease pool of its own.
//!
//! Text from password managers is never read: the first item on the
//! pasteboard is checked for the markers of nspasteboard.org
//! (`org.nspasteboard.ConcealedType`, `TransientType`, `AutoGeneratedType`)
//! before its text is asked for. Nothing here logs, and errors never carry
//! clipboard text.

use std::panic::{AssertUnwindSafe, catch_unwind};
use std::sync::mpsc::{self, RecvTimeoutError};
use std::sync::{Arc, Mutex};
use std::thread;
use std::time::{Duration, Instant};

use hop_platform::{CLIPBOARD_TIMEOUT, PlatformError, Result, TextClipboard, to_lf};
use objc2::rc::{Retained, autoreleasepool};
use objc2::runtime::NSObjectProtocol;
use objc2::{ClassType, msg_send, sel};
use objc2_app_kit::{NSPasteboard, NSPasteboardAccessBehavior, NSPasteboardTypeString};
use objc2_foundation::NSString;

use crate::shared::lock;

/// The pasteboard types that mark an item as never to be read or kept
/// (nspasteboard.org): password managers put them on the passwords they
/// copy. Type names compare without regard to case, as macOS compares
/// them.
const PRIVATE_MARKERS: [&str; 3] = [
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
];

/// Finds the pasteboard to use, on the helper thread, for each call.
type Opener = dyn Fn() -> Option<Retained<NSPasteboard>> + Send + Sync;

/// One call's work, run on the helper thread with the opener.
type Job = Box<dyn FnOnce(&Opener) + Send>;

/// [`TextClipboard`] for macOS.
pub(crate) struct MacClipboard {
    /// The pasteboard: the general one, except in tests.
    open: Arc<Opener>,
    /// The helper thread's queue, once a call has started it.
    jobs: Mutex<Option<mpsc::Sender<Job>>>,
    /// How long a caller waits for the helper: [`CLIPBOARD_TIMEOUT`], except
    /// in tests.
    timeout: Duration,
}

impl MacClipboard {
    /// The clipboard everyone copies to and pastes from. Nothing is read,
    /// and no thread started, until the first call.
    pub(crate) fn new() -> Self {
        Self::with_pasteboard(general_pasteboard, CLIPBOARD_TIMEOUT)
    }

    /// A clipboard on whatever pasteboard `open` finds (run on the helper
    /// thread for each call), whose callers wait at most `timeout`.
    fn with_pasteboard(
        open: impl Fn() -> Option<Retained<NSPasteboard>> + Send + Sync + 'static,
        timeout: Duration,
    ) -> Self {
        Self {
            open: Arc::new(open),
            jobs: Mutex::new(None),
            timeout,
        }
    }

    /// Runs `work` on the helper thread and waits for its answer, at most
    /// until the deadline.
    fn call<R: Send + 'static>(
        &self,
        work: impl FnOnce(&NSPasteboard) -> Result<R> + Send + 'static,
    ) -> Result<R> {
        let deadline = Instant::now() + self.timeout;
        let (reply, answer) = mpsc::sync_channel(1);
        let job: Job = Box::new(move |open: &Opener| {
            // The caller has given up and returned an error: acting now
            // would only surprise the user.
            if Instant::now() >= deadline {
                return;
            }
            let outcome = catch_unwind(AssertUnwindSafe(|| {
                autoreleasepool(|_| match open() {
                    Some(pasteboard) => work(&pasteboard),
                    None => Err(PlatformError::Os(
                        "macOS has no clipboard for Hop (no window-server session)".into(),
                    )),
                })
            }));
            let outcome = outcome
                .unwrap_or_else(|_| Err(PlatformError::Os("the clipboard code panicked".into())));
            // The caller may have timed out and gone; that is fine.
            let _ = reply.send(outcome);
        });
        self.submit(job)?;
        match answer.recv_timeout(deadline.saturating_duration_since(Instant::now())) {
            Ok(outcome) => outcome,
            Err(RecvTimeoutError::Timeout | RecvTimeoutError::Disconnected) => {
                Err(PlatformError::Os(format!(
                    "the clipboard did not answer within {} ms (the app that copied may be busy)",
                    self.timeout.as_millis()
                )))
            }
        }
    }

    /// Hands `job` to the helper thread, starting it first if it is not
    /// running (the first call, or a helper that died).
    fn submit(&self, job: Job) -> Result<()> {
        let mut jobs = lock(&self.jobs);
        let job = match jobs.as_ref() {
            Some(sender) => match sender.send(job) {
                Ok(()) => return Ok(()),
                Err(mpsc::SendError(job)) => job,
            },
            None => job,
        };
        let (sender, receiver) = mpsc::channel::<Job>();
        let open = Arc::clone(&self.open);
        thread::Builder::new()
            .name("hop-clipboard".into())
            .spawn(move || {
                // One call at a time, until the clipboard is dropped.
                for job in receiver {
                    job(&*open);
                }
            })
            .map_err(|error| {
                PlatformError::Os(format!("could not start the clipboard thread: {error}"))
            })?;
        // A new channel's receiver is alive, so this cannot fail.
        let _ = sender.send(job);
        *jobs = Some(sender);
        Ok(())
    }
}

impl TextClipboard for MacClipboard {
    fn change_count(&self) -> Result<u64> {
        self.call(|pasteboard| Ok(change_count(pasteboard)))
    }

    fn read_text(&self, max_bytes: usize) -> Result<Option<String>> {
        self.call(move |pasteboard| read_text(pasteboard, max_bytes))
    }

    fn write_text(&mut self, text: &str) -> Result<u64> {
        let text = text.to_owned();
        self.call(move |pasteboard| write_text(pasteboard, &text))
    }
}

/// The general pasteboard. `generalPasteboard` is documented never to
/// return nil, but it can (a process started by launchd without a
/// window-server session, say), so it is asked for as an optional.
fn general_pasteboard() -> Option<Retained<NSPasteboard>> {
    // SAFETY: `generalPasteboard` takes no arguments and returns the shared
    // pasteboard object, or nil, which the `Option` covers.
    unsafe { msg_send![NSPasteboard::class(), generalPasteboard] }
}

/// The pasteboard's change count. macOS counts from zero, upward.
fn change_count(pasteboard: &NSPasteboard) -> u64 {
    u64::try_from(pasteboard.changeCount()).unwrap_or(0)
}

/// The text of the pasteboard's first item, with LF line endings. `None`
/// when that item has no text or only empty text, is marked private, or
/// has more than `max_bytes` of UTF-8 text (it is never cut short).
fn read_text(pasteboard: &NSPasteboard, max_bytes: usize) -> Result<Option<String>> {
    check_access(pasteboard)?;
    let Some(item) = pasteboard
        .pasteboardItems()
        .and_then(|items| items.firstObject())
    else {
        return Ok(None);
    };
    let types: Vec<String> = item.types().iter().map(|ty| ty.to_string()).collect();
    if is_private(&types) {
        return Ok(None);
    }
    // SAFETY: reading an immutable AppKit constant.
    let string_type = unsafe { NSPasteboardTypeString };
    let Some(text) = item.stringForType(string_type) else {
        return Ok(None);
    };
    // Empty text is no text, as on Windows: sending it would only empty the
    // other computer's clipboard. `pbcopy < /dev/null` leaves an empty
    // string on the pasteboard, and so does text with a broken character
    // that macOS cannot keep. LF endings never make other text empty.
    if text.length() == 0 {
        return Ok(None);
    }
    // Every UTF-16 unit is at least one UTF-8 byte, and turning CRLF into
    // LF at most halves the count: longer than this, it can never fit, and
    // a huge text is not copied out just to find that out.
    if text.length() / 2 > max_bytes {
        return Ok(None);
    }
    Ok(fitting(&text.to_string(), max_bytes))
}

/// `text` with LF line endings, unless that is more than `max_bytes` long.
fn fitting(text: &str, max_bytes: usize) -> Option<String> {
    let text = to_lf(text);
    (text.len() <= max_bytes).then(|| text.into_owned())
}

/// Whether an item with these types comes from a password manager (or
/// another app that asks for its text never to be read or kept).
fn is_private(types: &[String]) -> bool {
    types.iter().any(|ty| {
        PRIVATE_MARKERS
            .iter()
            .any(|marker| marker.eq_ignore_ascii_case(ty))
    })
}

/// Puts `text` on the pasteboard in place of everything there, and returns
/// the change count right after.
fn write_text(pasteboard: &NSPasteboard, text: &str) -> Result<u64> {
    pasteboard.clearContents();
    // SAFETY: reading an immutable AppKit constant.
    let string_type = unsafe { NSPasteboardTypeString };
    if !pasteboard.setString_forType(&NSString::from_str(text), string_type) {
        return Err(PlatformError::Os(
            "macOS refused the text for the clipboard".into(),
        ));
    }
    Ok(change_count(pasteboard))
}

/// Fails if the user told macOS never to let Hop read the clipboard. The
/// setting exists from macOS 15.4 on (`accessBehavior`); before that every
/// read is allowed.
fn check_access(pasteboard: &NSPasteboard) -> Result<()> {
    if pasteboard.respondsToSelector(sel!(accessBehavior)) {
        allowed(pasteboard.accessBehavior())
    } else {
        Ok(())
    }
}

/// Whether reading is allowed under `behavior`: everything but "always
/// deny" is (macOS itself asks the user where it is set to ask), and that
/// one gets an error saying where to change it.
fn allowed(behavior: NSPasteboardAccessBehavior) -> Result<()> {
    if behavior == NSPasteboardAccessBehavior::AlwaysDeny {
        return Err(PlatformError::Os(
            "macOS does not let Hop read the clipboard: allow it in System Settings > Privacy & \
             Security > Paste from Other Apps"
                .into(),
        ));
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    //! Every test uses a private pasteboard of its own
    //! (`pasteboardWithUniqueName`), never the general one: nothing here
    //! reads or changes what the user copied.

    use std::sync::mpsc::Receiver;

    use objc2_app_kit::NSPasteboardItem;
    use objc2_foundation::ns_string;

    use super::*;
    use crate::private_pasteboard::PrivatePasteboard as Private;

    /// Long enough that a loaded test machine never times out a call that
    /// works; the timeout tests set their own.
    const PATIENT: Duration = Duration::from_secs(10);

    impl Private {
        /// A clipboard on this pasteboard: the helper finds it by name.
        fn clipboard(&self, timeout: Duration) -> MacClipboard {
            MacClipboard::with_pasteboard(self.opener(), timeout)
        }

        /// Puts one item with `text` (if any) and the extra `types` (as
        /// empty strings) on the pasteboard, as another app would.
        fn put(&self, text: Option<&str>, types: &[&str]) {
            let item = NSPasteboardItem::new();
            // SAFETY: reading an immutable AppKit constant.
            let string_type = unsafe { NSPasteboardTypeString };
            if let Some(text) = text {
                assert!(item.setString_forType(&NSString::from_str(text), string_type));
            }
            for ty in types {
                assert!(item.setString_forType(ns_string!(""), &NSString::from_str(ty)));
            }
            self.write(vec![item]);
        }
    }

    #[test]
    fn text_goes_on_and_comes_back() {
        let private = Private::new();
        let mut clipboard = private.clipboard(PATIENT);
        let count = clipboard.write_text("one\ntwo").expect("write");
        assert_eq!(clipboard.change_count().expect("count"), count);
        assert_eq!(
            clipboard.read_text(1024).expect("read").as_deref(),
            Some("one\ntwo")
        );
        // Another app sees the same text.
        // SAFETY: reading an immutable AppKit constant.
        let string_type = unsafe { NSPasteboardTypeString };
        let seen = private.pasteboard.stringForType(string_type);
        assert_eq!(seen.map(|s| s.to_string()).as_deref(), Some("one\ntwo"));
    }

    #[test]
    fn every_write_moves_the_change_count_on() {
        let private = Private::new();
        let mut clipboard = private.clipboard(PATIENT);
        let start = clipboard.change_count().expect("count");
        let first = clipboard.write_text("first").expect("write");
        let second = clipboard.write_text("second").expect("write");
        assert!(start < first && first < second, "{start} {first} {second}");
        assert_eq!(change_count(&private.pasteboard), second);
        // Reading changes nothing.
        clipboard.read_text(1024).expect("read");
        assert_eq!(clipboard.change_count().expect("count"), second);
        // Another app's copy moves it on too.
        private.put(Some("from another app"), &[]);
        assert!(clipboard.change_count().expect("count") > second);
    }

    #[test]
    fn line_endings_come_back_as_lf() {
        let private = Private::new();
        let clipboard = private.clipboard(PATIENT);
        private.put(Some("a\r\nb\rc\nd"), &[]);
        assert_eq!(
            clipboard.read_text(1024).expect("read").as_deref(),
            Some("a\nb\nc\nd")
        );
    }

    #[test]
    fn password_managers_items_are_never_read() {
        let private = Private::new();
        let clipboard = private.clipboard(PATIENT);
        for marker in PRIVATE_MARKERS {
            private.put(Some("secret"), &[marker]);
            assert_eq!(clipboard.read_text(1024).expect("read"), None, "{marker}");
        }
        // Only the first item counts: a marker on a later one does not hide
        // the first item's text.
        // SAFETY: reading an immutable AppKit constant.
        let string_type = unsafe { NSPasteboardTypeString };
        let first = NSPasteboardItem::new();
        assert!(first.setString_forType(ns_string!("plain"), string_type));
        let second = NSPasteboardItem::new();
        let marker = NSString::from_str(PRIVATE_MARKERS[0]);
        assert!(second.setString_forType(ns_string!("x"), &marker));
        private.write(vec![first, second]);
        assert_eq!(
            clipboard.read_text(1024).expect("read").as_deref(),
            Some("plain")
        );
    }

    #[test]
    fn markers_are_recognised_by_name() {
        let types = |names: &[&str]| names.iter().map(|n| n.to_string()).collect::<Vec<_>>();
        assert!(!is_private(&types(&["public.utf8-plain-text"])));
        assert!(is_private(&types(&[
            "public.utf8-plain-text",
            "org.nspasteboard.TransientType"
        ])));
        assert!(is_private(&types(&["org.nspasteboard.AutoGeneratedType"])));
        // Spelled in any case: macOS treats type names that way.
        assert!(is_private(&types(&["org.nspasteboard.concealedtype"])));
        assert!(!is_private(&types(&["org.nspasteboard.Concealed"])));
        assert!(!is_private(&[]));
    }

    #[test]
    fn text_over_the_limit_is_never_cut_short() {
        let private = Private::new();
        let clipboard = private.clipboard(PATIENT);
        // Six bytes of UTF-8 in five characters.
        private.put(Some("héllo"), &[]);
        assert_eq!(clipboard.read_text(5).expect("read"), None);
        assert_eq!(
            clipboard.read_text(6).expect("read").as_deref(),
            Some("héllo")
        );
        // The limit applies to the text as Hop sends it: with LF endings.
        private.put(Some("a\r\nb\r\n"), &[]);
        assert_eq!(
            clipboard.read_text(4).expect("read").as_deref(),
            Some("a\nb\n")
        );
        assert_eq!(clipboard.read_text(3).expect("read"), None);
        // Far too long is turned down without copying it out.
        private.put(Some(&"x".repeat(10_000)), &[]);
        assert_eq!(clipboard.read_text(100).expect("read"), None);
        assert_eq!(fitting("abc", 3).as_deref(), Some("abc"));
        assert_eq!(fitting("abcd", 3), None);
        assert_eq!(fitting("", 0).as_deref(), Some(""));
    }

    #[test]
    fn a_clipboard_without_text_reads_as_none() {
        let private = Private::new();
        let clipboard = private.clipboard(PATIENT);
        assert_eq!(clipboard.read_text(1024).expect("read"), None, "empty");
        private.put(None, &["public.png"]);
        assert_eq!(clipboard.read_text(1024).expect("read"), None, "no text");
        // Empty text, as `pbcopy < /dev/null` leaves it, is no text either:
        // sending it would empty the other computer's clipboard.
        private.put(Some(""), &[]);
        let count = clipboard.change_count().expect("count");
        assert_eq!(clipboard.read_text(1024).expect("read"), None, "empty text");
        // The change count still moved, so the agent records the copy and
        // does not ask again until the next one.
        private.put(Some(" "), &[]);
        assert!(clipboard.change_count().expect("count") > count);
        assert_eq!(
            clipboard.read_text(1024).expect("read").as_deref(),
            Some(" "),
            "a space is text"
        );
    }

    #[test]
    fn written_empty_text_reads_back_as_none() {
        // Writing goes through as asked (the other computer never sends
        // empty text, but nothing here relies on that); reading it back
        // finds no text.
        let private = Private::new();
        let mut clipboard = private.clipboard(PATIENT);
        let count = clipboard.write_text("").expect("write");
        assert_eq!(clipboard.change_count().expect("count"), count);
        assert_eq!(clipboard.read_text(1024).expect("read"), None);
    }

    /// A clipboard on `private` whose helper hangs in its first call, as it
    /// would on an app that copied lazily and then stopped answering, until
    /// the returned sender sends (or is dropped). Later calls go through at
    /// once.
    fn hanging(private: &Private, timeout: Duration) -> (MacClipboard, mpsc::Sender<()>) {
        let (release, hold) = mpsc::channel::<()>();
        let hold: Mutex<Option<Receiver<()>>> = Mutex::new(Some(hold));
        let pasteboard = private.opener();
        let open = move || {
            if let Some(hold) = lock(&hold).take() {
                let _ = hold.recv();
            }
            pasteboard()
        };
        (MacClipboard::with_pasteboard(open, timeout), release)
    }

    #[test]
    fn a_helper_that_never_answers_times_out_within_the_bound() {
        let private = Private::new();
        let (mut clipboard, release) = hanging(&private, CLIPBOARD_TIMEOUT);
        let start = Instant::now();
        let outcome = clipboard.change_count();
        let waited = start.elapsed();
        assert!(outcome.is_err());
        assert!(waited >= CLIPBOARD_TIMEOUT, "{waited:?}");
        assert!(waited < CLIPBOARD_TIMEOUT * 4, "{waited:?}");
        // The error says what happened, and nothing of the clipboard.
        let message = outcome.unwrap_err().to_string();
        assert!(
            message.contains("did not answer within 250 ms"),
            "{message}"
        );
        // Once the app answers, the helper carries on.
        release.send(()).expect("release");
        clipboard.timeout = PATIENT;
        assert!(clipboard.change_count().is_ok());
    }

    #[test]
    fn a_call_whose_caller_gave_up_is_never_carried_out() {
        let private = Private::new();
        let (mut clipboard, release) = hanging(&private, Duration::from_millis(50));
        // The first call hangs the helper; the write waits behind it, and
        // both callers give up.
        assert!(clipboard.change_count().is_err());
        assert!(clipboard.write_text("late").is_err());
        // The app answers at last. The hung call finishes; the write, whose
        // caller is long gone, is skipped rather than replacing whatever
        // was copied since.
        release.send(()).expect("release");
        clipboard.timeout = PATIENT;
        assert_eq!(clipboard.read_text(1024).expect("read"), None);
        assert_eq!(clipboard.change_count().expect("count"), 0, "never written");
        // And the helper still works.
        let count = clipboard.write_text("on time").expect("write");
        assert_eq!(change_count(&private.pasteboard), count);
    }

    #[test]
    fn only_always_deny_keeps_hop_from_reading() {
        for behavior in [
            NSPasteboardAccessBehavior::Default,
            NSPasteboardAccessBehavior::Ask,
            NSPasteboardAccessBehavior::AlwaysAllow,
        ] {
            assert!(allowed(behavior).is_ok(), "{behavior:?}");
        }
        let message = allowed(NSPasteboardAccessBehavior::AlwaysDeny)
            .unwrap_err()
            .to_string();
        assert!(
            message.contains("System Settings > Privacy & Security > Paste from Other Apps"),
            "{message}"
        );
        // A private pasteboard is always readable, whatever the general one
        // is set to.
        let private = Private::new();
        assert!(check_access(&private.pasteboard).is_ok());
    }

    #[test]
    fn building_the_clipboard_touches_nothing() {
        // No pasteboard is opened and no thread started until a call.
        let clipboard = MacClipboard::new();
        assert!(lock(&clipboard.jobs).is_none());
        assert_eq!(clipboard.timeout, CLIPBOARD_TIMEOUT);
    }
}
