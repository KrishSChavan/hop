use serde::{Deserialize, Serialize};

/// A key identified by its USB HID usage, `(page << 16) | usage`.
///
/// This names a physical key position, not a character: the receiving OS
/// applies its own keyboard layout.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
#[serde(transparent)]
pub struct KeyCode(pub u32);

impl KeyCode {
    pub const KEYBOARD_PAGE: u16 = 0x07;
    pub const CONSUMER_PAGE: u16 = 0x0C;

    pub const LEFT_CONTROL: KeyCode = KeyCode::keyboard(0xE0);
    pub const LEFT_SHIFT: KeyCode = KeyCode::keyboard(0xE1);
    /// Option on a Mac keyboard, Alt on a PC keyboard.
    pub const LEFT_ALT: KeyCode = KeyCode::keyboard(0xE2);
    /// Command on a Mac keyboard, the Windows key on a PC keyboard.
    pub const LEFT_META: KeyCode = KeyCode::keyboard(0xE3);
    pub const RIGHT_CONTROL: KeyCode = KeyCode::keyboard(0xE4);
    pub const RIGHT_SHIFT: KeyCode = KeyCode::keyboard(0xE5);
    pub const RIGHT_ALT: KeyCode = KeyCode::keyboard(0xE6);
    pub const RIGHT_META: KeyCode = KeyCode::keyboard(0xE7);
    pub const CAPS_LOCK: KeyCode = KeyCode::keyboard(0x39);
    pub const ESCAPE: KeyCode = KeyCode::keyboard(0x29);

    /// A key on the keyboard usage page (0x07).
    pub const fn keyboard(usage: u16) -> Self {
        KeyCode(((Self::KEYBOARD_PAGE as u32) << 16) | usage as u32)
    }

    /// A key on the consumer usage page (0x0C): media and volume keys.
    pub const fn consumer(usage: u16) -> Self {
        KeyCode(((Self::CONSUMER_PAGE as u32) << 16) | usage as u32)
    }

    pub const fn page(self) -> u16 {
        (self.0 >> 16) as u16
    }

    pub const fn usage(self) -> u16 {
        (self.0 & 0xFFFF) as u16
    }

    /// Control, Shift, Alt/Option or Meta/Command/Windows, either side.
    pub const fn is_modifier(self) -> bool {
        self.page() == Self::KEYBOARD_PAGE && self.usage() >= 0xE0 && self.usage() <= 0xE7
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum MouseButton {
    Left,
    Right,
    Middle,
    Back,
    Forward,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum ScrollUnit {
    /// Wheel notches (one notch = 1.0).
    Line,
    /// Smooth scrolling in logical units, e.g. from a trackpad.
    Pixel,
}

/// An input event in OS-independent form.
#[derive(Clone, Copy, Debug, PartialEq, Serialize, Deserialize)]
pub enum InputEvent {
    /// Relative pointer motion in the source device's logical units, already
    /// shaped by the source OS (its acceleration applied).
    PointerMotion {
        dx: f64,
        dy: f64,
    },
    Button {
        button: MouseButton,
        pressed: bool,
    },
    /// Positive `dy` means the wheel moved forward (away from the user);
    /// positive `dx` means scroll right. Natural-scrolling inversion is the
    /// source OS's business and is already applied.
    Scroll {
        dx: f64,
        dy: f64,
        unit: ScrollUnit,
    },
    /// `repeat` is true for auto-repeat key-downs generated by the source OS.
    Key {
        code: KeyCode,
        pressed: bool,
        repeat: bool,
    },
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn key_code_parts() {
        let a = KeyCode::keyboard(0x04);
        assert_eq!(a.page(), 0x07);
        assert_eq!(a.usage(), 0x04);
        assert!(!a.is_modifier());
        assert!(KeyCode::LEFT_META.is_modifier());
        assert!(KeyCode::RIGHT_META.is_modifier());
        assert!(!KeyCode::consumer(0xE9).is_modifier());
    }
}
